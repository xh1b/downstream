"""Export evidence roles without promoting observed associations to causal effects."""
from __future__ import annotations

import argparse
from collections import Counter
import csv
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def _rows(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(line for line in handle if not line.startswith("#")))


def inventory(params_dir: Path) -> dict:
    from downstream.evidence import load_corpus, load_findings
    from downstream.ledger import CHAIN_CAUSAL_ROLES, CHAIN_KINDS
    from downstream.params import load, load_baselines, load_correlations
    from downstream.study_library import load_library
    from downstream.transmissions import TRANSMISSIONS

    params = load(params_dir / "parameters.csv")
    shares = {step.share for transmission in TRANSMISSIONS for step in transmission.steps
              if step.share}
    parameters = []
    for p in params.parameters:
        chain_role = CHAIN_CAUSAL_ROLES.get(p.link)
        if p.link in shares:
            use = "observed_counterfactual_share"
        elif chain_role:
            use = chain_role
        elif p.evidence_role == "structural":
            use = "structural_assumption_or_modifier"
        elif p.evidence_role == "boundary":
            use = "separate_exposure_or_association; named_adapter_only"
        else:
            use = "conditional_effect; named_adapter_only"
        parameters.append({"link": p.link, "evidence_role": p.evidence_role,
                           "runtime_use": use, "chain_kind": CHAIN_KINDS.get(p.link),
                           "citation": p.citation, "tier": p.tier})
    corpus = load_corpus(params_dir / "evidence_corpus.csv")
    findings = load_findings(params_dir / "evidence_findings.csv")
    contrasts = load_library(params_dir / "study_estimates.csv")
    baselines = load_baselines(params_dir / "baselines.csv")
    transitions = _rows(params_dir / "baseline_employment_transitions.csv")
    files = ["VERSION", "parameters.csv", "baselines.csv", "mortality_profiles.csv",
             "baseline_employment_transitions.csv", "correlations.csv", "evidence_corpus.csv",
             "evidence_findings.csv", "study_estimates.csv",
             "../src/downstream/params.py", "../src/downstream/ledger.py",
             "../src/downstream/transmissions.py", "../src/downstream/evidence.py",
             "../src/downstream/study_library.py", "../src/downstream/admission.py",
             "../src/downstream/household.py"]
    return {"version": params.version, "parameters": parameters, "baselines": baselines,
            "transitions": transitions, "profiles": _rows(params_dir / "mortality_profiles.csv"),
            "correlations": load_correlations(params_dir / "correlations.csv"),
            "corpus": corpus, "findings": findings, "contrasts": contrasts,
            "source_sha256": {name: hashlib.sha256((params_dir / name).read_bytes()).hexdigest()
                              for name in files}}


def _cell(value) -> str:
    return str(value if value is not None else "—").replace("|", "\\|").replace("\n", " ")


def _table(headers, rows) -> list[str]:
    return ["| " + " | ".join(headers) + " |",
            "| " + " | ".join("---" for _ in headers) + " |",
            *("| " + " | ".join(_cell(value) for value in row) + " |" for row in rows)]


