def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--params-dir", type=Path, default=ROOT / "params")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/EVIDENCE_CLASSIFICATION_0_4.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    report = render(inventory(args.params_dir))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != report:
            print(f"stale evidence classification: {args.output}", file=sys.stderr)
            return 1
        print(f"current evidence classification: {args.output}")
    else:
        args.output.write_text(report, encoding="utf-8")
        print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
